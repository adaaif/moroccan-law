#!/usr/bin/env sh
# Writes lock.txt: every package of base.txt, dev.txt and prod.txt with all their dependencies, pinned with their
# hashes, for `pip install --require-hashes -r lock.txt` (CI). The local Rust package (../crates/ma-py) stays outside
# it: CI builds it from crates/. Needs pip-tools, best in a venv of its own:
#
#   back/requirements/lock.sh                    the newest versions the three files allow
#   back/requirements/lock.sh constraints.txt    none newer than a working environment's (pip freeze > constraints.txt)
set -eu
here="$(cd "$(dirname "$0")" && pwd)"
grep -hv -e '^\.\./crates' -e '^-r ' "$here/base.txt" "$here/dev.txt" "$here/prod.txt" \
  | pip-compile --quiet --no-header --generate-hashes --allow-unsafe --strip-extras ${1:+--constraint "$1"} \
      --output-file "$here/lock.txt.part" -
# The annotations name the three files, never a constraints file's place on this machine.
{
  echo "# Generated by back/requirements/lock.sh from base.txt, dev.txt and prod.txt (without ../crates/ma-py): do not edit."
  sed -e '/^    #   -c /d' -e 's|^    #   -r -$|    #   base.txt, dev.txt or prod.txt|' \
      -e 's|^    # via -r -$|    # via base.txt, dev.txt or prod.txt|' "$here/lock.txt.part"
} > "$here/lock.txt"
rm -f "$here/lock.txt.part"
