    assert rows['segma_balance'] == 0
    assert rows['segma_investment'] == Decimal('257133000')
    assert rows['amortisation_internal'] == Decimal('48246100000')
    assert rows['borrowing_internal'] == Decimal('63000000000')
    assert rows['remaining_needs'] == Decimal('-48744349000')


