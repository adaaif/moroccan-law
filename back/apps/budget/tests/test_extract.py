def test_amounts_are_read_with_their_groups_decimals_and_sign():
    assert [a for a, _, _ in amounts_in('… 421.325.037.000')] == [Decimal('421325037000')]
    assert [a for a, _, _ in amounts_in('(5) = (4)-(3) .... -106.323.002.000')] == [Decimal('-106323002000')]
    assert [a for a, _, _ in amounts_in('| 26 292 000 | 38.562,85 |')] == [Decimal('26292000'), Decimal('38562.85')]
    assert [a for a, _, _ in amounts_in('بناء على الفصول 42 و 50 لسنة 2026')] == [Decimal('2026')]


