PACKED = '**وزارة العدل**<br>مركز نشر المعلومة القانونية<br>المعهد الوطني لكتابة الضبط<br>**مجموع وزارة العدل**'
UNPACKED = [('4.2.1.1.0.06.002', 'وزارة العدل', 'مركز نشر المعلومة القانونية', 2000000, False),
            ('4.2.1.1.0.06.003', 'وزارة العدل', 'المعهد الوطني لكتابة الضبط', 3500000, False),
            ('', 'وزارة العدل', 'مجموع وزارة العدل', 5500000, True)]


@pytest.mark.parametrize('codes, amounts, expected', [
    # The heading's own empty figure, or a code part for every label (the heading's and the total's empty): one row each.
    ('4.2.1.1.0.06.002<br>4.2.1.1.0.06.003', '<br>2 000 000<br>3 500 000<br>5 500 000', UNPACKED),
    ('<br>4.2.1.1.0.06.002<br>4.2.1.1.0.06.003<br>', '2 000 000<br>3 500 000<br>5 500 000', UNPACKED),
    # More codes than rows, or fewer figures: the row cannot be parted, its figures go to no line (never guessed),
    # and its heading still names the ministry of the rows under it.
    ('4.2.1.1.0.06.002<br>4.2.1.1.0.06.003<br>4.2.1.1.0.06.004', '2 000 000<br>3 500 000<br>5 500 000', []),
    ('4.2.1.1.0.06.002<br>4.2.1.1.0.06.003', '2 000 000<br>3 500 000', []),
])
def test_a_packed_row_is_unpacked_when_its_cells_line_up_and_read_for_no_figure_when_they_do_not(codes, amounts,
                                                                                                  expected):
    rows = parse_coded_table([(9732, f'| {codes} | {PACKED} | {amounts} |'),
                              (9733, '| | 5 500 000 |'),          # a row of figures alone, its words lost: no line
                              (9733, '| 4.2.1.1.0.06.009 | مركز التكوين | 1 000 |')])
    assert [(r['code'], r['section'], r['label'], r['amounts'][0], r['is_total']) for r in rows] == expected + [
        ('4.2.1.1.0.06.009', 'وزارة العدل', 'مركز التكوين', 1000, False)]
